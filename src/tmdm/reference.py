"""Reference definitions: commodities, partner codes, ports and trade routes.

A route is one origin economy, one destination economy and one commodity
group, measured from the customs data of the reporter named in the route
(the exporter wherever the exporter publishes timely monthly data, otherwise
the importer). Loading and discharge ports are representative ports taken
from the World Port Index; where a trade loads at several terminals the
route distance is a weighted blend of the port distances, with the weights
documented here.

Routes between land neighbours (for example United States to Mexico grain,
Russia and Mongolia to China coal) are excluded because customs data do not
separate rail and truck from sea transport.
"""

